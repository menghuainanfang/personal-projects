"""Generate larger, reproducible, independently held-out teacher sets.

This generator only produces teacher datasets; model training, learned field
encoding and PDE benchmarks are follow-up implementation tasks for Work.
Examples:
  python dataset_factory.py --preset smoke --output ../runs/smoke
  python dataset_factory.py --preset gaussian_1200 --output ../runs/gaussian_1200
  python dataset_factory.py --preset gaussian_3000 --output ../runs/gaussian_3000
  python dataset_factory.py --preset mixed_2400 --output ../runs/mixed_2400
"""
import argparse, hashlib, json, math, sys
from pathlib import Path
import numpy as np
from teacher_general import make_teacher


def sample_gaussian(group: str, n: int, seed: int):
    r = np.random.default_rng(seed)
    cases = []
    for _ in range(n):
        mu = [r.uniform(.30,.70), r.uniform(.30,.70), r.uniform(2,8),r.uniform(.18,.30)]
        if group == 'center':
            ax = int(r.integers(0,2))
            mu[ax] = float(r.uniform(.12,.27) if r.random() < .5 else r.uniform(.73,.88))
        elif group == 'narrow':
            mu = r.uniform([.25,.25,10,.08],[.75,.75,14,.14]).tolist()
        elif group == 'broad':
            mu = r.uniform([.25,.25,.5,.34],[.75,.75,1.5,.42]).tolist()
        elif group != 'ID':raise ValueError(group)
        cases.append({'kind':'single','mu':[float(v) for v in mu]})
    return cases


def sample_double(n: int, seed: int):
    r=np.random.default_rng(seed);out=[]
    while len(out)<n:
        c1=r.uniform(.18,.82,size=2);c2=r.uniform(.18,.82,size=2)
        if np.linalg.norm(c1-c2)<.22:continue
        peaks=[[float(c1[0]),float(c1[1]),float(r.uniform(3,8)),float(r.uniform(.085,.18))],
               [float(c2[0]),float(c2[1]),float(r.uniform(2,6)),float(r.uniform(.085,.18))]]
        # Canonical peak order by x, then y, to prevent permutation ambiguity.
        out.append({'kind':'double','peaks':sorted(peaks,key=lambda p:(p[0],p[1]))})
    return out


def sample_wave(n:int,seed:int):
    r=np.random.default_rng(seed)
    return [{'kind':'wave','phase':float(r.uniform(-math.pi, math.pi)),
             'strength':float(r.uniform(4,12)),'width':float(r.uniform(.07,.15))}
            for _ in range(n)]


def shared_old_140():
    # Exact parameters generated by previous pilot.draw_train_params('ID', 140, 61001).
    r=np.random.default_rng(61001)
    return [{'kind':'single','mu':[float(r.uniform(.3,.7)),float(r.uniform(.3,.7)),
                                   float(r.uniform(2,8)),float(r.uniform(.18,.30))]}
            for _ in range(140)]


def specs(preset:str):
    if preset=='smoke':
        return {'train':sample_gaussian('ID',4,61002)+sample_gaussian('narrow',4,61003)
                +sample_double(3,61004)+sample_wave(3,61005),
                'validation':sample_gaussian('center',4,61101),
                'test':sample_gaussian('broad',4,61201)}
    if preset in ('gaussian_1200','gaussian_3000'):
        groups={'gaussian_1200':(160,300),'gaussian_3000':(610,750)}
        extra_id,each=groups[preset]
        train=shared_old_140()+sample_gaussian('ID',extra_id,81001)
        for i,g in enumerate(('center','narrow','broad')):
            train+=sample_gaussian(g,each,81002+i)
        assert len(train) == (1200 if preset=='gaussian_1200' else 3000)
        return dict(train=train,
                    validation=sum((sample_gaussian(g,100,82000+i) for i,g in enumerate(('ID','center','narrow','broad'))),[]),
                    test=sum((sample_gaussian(g,100,83000+i) for i,g in enumerate(('ID','center','narrow','broad'))),[]))
    if preset=='mixed_2400':
        train=shared_old_140()+sample_gaussian('ID',260,91000)
        for i,g in enumerate(('center','narrow','broad')):train+=sample_gaussian(g,400,91001+i)
        train+=sample_double(600,91010)+sample_wave(200,91011)
        assert len(train)==2400
        return dict(train=train,
                    validation=sum((sample_gaussian(g,60,92000+i) for i,g in enumerate(('ID','center','narrow','broad'))),[])
                       +sample_double(80,92010)+sample_wave(80,92011),
                    test=sum((sample_gaussian(g,80,93000+i) for i,g in enumerate(('ID','center','narrow','broad'))),[])
                       +sample_double(100,93010)+sample_wave(100,93011))
    raise ValueError('Unknown preset')


def kind_group(spec):
    if spec['kind']!='single':return spec['kind']
    c=spec['mu'];cx,cy,a,w=c
    if a>9 and w<.16:return 'narrow'
    if a<2 and w>.3:return 'broad'
    if cx<.28 or cx>.72 or cy<.28 or cy>.72:return 'center'
    return 'ID'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--preset',choices=['smoke','gaussian_1200','gaussian_3000','mixed_2400'],required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--resolutions',type=int,nargs='+',default=[12],help='n squares per axis, e.g. 8 12 16 24')
    parser.add_argument('--limit',type=int,default=0,help='Temporary sample cap per split; 0 is unlimited')
    args=parser.parse_args();out=args.output.resolve();out.mkdir(parents=True,exist_ok=True)
    library=specs(args.preset)
    manifest={'preset':args.preset,'resolutions':args.resolutions,'source':'independent teacher_general.py',
              'splits':{},'requested':{},'valid':{},'failed':{},'scope':'Frozen-X0 Q quadratic teacher; physical energy not optimized'}
    # Immutable user-provided archived baseline is never opened for writes.
    for split,items in library.items():
        selected=items[:args.limit] if args.limit else items
        records=[];failures=[]
        for j,spec in enumerate(selected):
            n=int(args.resolutions[j%len(args.resolutions)])
            fingerprint=json.dumps({'spec':spec,'n':n},sort_keys=True,separators=(',',':'))
            uid=hashlib.sha256(fingerprint.encode()).hexdigest()[:20]
            dst=out/'teachers'/f'{uid}.npz'
            note=out/'teachers'/f'{uid}.json'
            try:
                if not (dst.exists() and note.exists()):
                    result=make_teacher(n,spec)
                    dst.parent.mkdir(parents=True,exist_ok=True)
                    np.savez_compressed(dst,X0=result['X0'],Q=result['Q'],X=result['X'],
                        cells=result['cells'],boundary=result['boundary'],monitor_cells=result['monitor_cells'])
                    note.write_text(json.dumps({'spec':spec,'n':n,'energy':result['energy'],
                        'residual':result['residual'],'q_min_area':result['q_min_area'],
                        'x_min_area':result['x_min_area'],'teacher_seconds':result['seconds']},indent=2),encoding='utf-8')
                records.append({'id':uid,'n':n,'group':kind_group(spec),'spec':spec,
                                'relative_data_path':str(dst.relative_to(out))})
            except Exception as exc:
                failures.append({'spec':spec,'n':n,'error':repr(exc)})
            if (j+1)%100==0:print(split,j+1,'/',len(selected),'valid',len(records),'failed',len(failures),flush=True)
        manifest['splits'][split]=records;manifest['requested'][split]=len(selected)
        manifest['valid'][split]=len(records);manifest['failed'][split]=len(failures)
        (out/f'failures_{split}.json').write_text(json.dumps(failures,ensure_ascii=False,indent=2),encoding='utf-8')
    ids=[{r['id'] for r in arr} for arr in manifest['splits'].values()]
    if any(ids[i]&ids[j] for i in range(len(ids)) for j in range(i+1,len(ids))):
        raise RuntimeError('Cross-split parameter duplicate (leakage)')
    (out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({key:manifest[key] for key in ['requested','valid','failed']},indent=2))
    if any(manifest['valid'][s]/max(manifest['requested'][s],1)<.90 for s in manifest['requested']):
        raise SystemExit('More than 10% teacher cases failed; investigate distribution / geometry before training.')

if __name__=='__main__':main()
